"""Unit tests of the error responses the CU00-CU03 admin-user routes declare in OpenAPI.

COUSR00C (CU00) answers an invalid selection code the re-browsed page still shows with a 400
whose body adds that page's rows, page, first_key and last_key to the four legacy keys
(app.services.users.cousr00c._InvalidSelectionRefusal). The declared responses must be complete
for the contract tests, as specified in the Technical Specification, Section 0.10.5:

- the 400 of POST /api/v1/admin/users/selection references UserSelectionErrorResponse, whose
    properties are exactly the keys of that body, and the body validates against the model
    unchanged;
- the 400 of the five other operations, and the selection's 401, 403 and 503, keep
    LegacyErrorResponse.

The document is generated by CreateApp from Settings whose engine never connects, so no
database is needed. SECRET_KEY is generated with the secrets module and backend/.env is never
read (_env_file=None).
"""

import secrets
from collections.abc import AsyncIterator
from typing import Any

import pytest
import pytest_asyncio

from app.core.config import Settings
from app.core.database import DisposeEngine
from app.schemas.users import UserListResponse, UserListRow, UserSelectionErrorResponse
from app.services.users import cousr00c

ALLOWED_ORIGIN = "http://127.0.0.1:3000"
# A well-formed URL of a database nobody creates: the engine is lazy and never connects.
UNUSED_DATABASE_URL = "postgresql+{driver}://openapi_test@127.0.0.1/openapi_test"
SECRET_KEY_BYTES = 32
TEST_APP_ENV = "test"

USERS_PATH = "/api/v1/admin/users"
SELECTION_PATH = "/api/v1/admin/users/selection"
USER_PATH = "/api/v1/admin/users/{userId}"
JSON_MEDIA_TYPE = "application/json"
SCHEMA_REFERENCE_PREFIX = "#/components/schemas/"
SELECTION_ERROR_MODEL = "UserSelectionErrorResponse"
LEGACY_ERROR_MODEL = "LegacyErrorResponse"
EDIT_FAILURE_STATUS = "400"

# The re-browsed page an invalid selection rides on: two users, page 1.
BROWSED_ROWS = [
    UserListRow(user_id="LISTU001", first_name="First", last_name="User", user_type="U"),
    UserListRow(user_id="LISTU002", first_name="Second", last_name="User", user_type="A"),
]
BROWSED_PAGE = 1

# The 400 of the five other operations and the selection's other errors: (method, path, status).
LEGACY_ERROR_CASES = [
    pytest.param("get", USERS_PATH, EDIT_FAILURE_STATUS, id="list-400"),
    pytest.param("post", USERS_PATH, EDIT_FAILURE_STATUS, id="add-400"),
    pytest.param("get", USER_PATH, EDIT_FAILURE_STATUS, id="fetch-400"),
    pytest.param("put", USER_PATH, EDIT_FAILURE_STATUS, id="update-400"),
    pytest.param("delete", USER_PATH, EDIT_FAILURE_STATUS, id="delete-400"),
    pytest.param("post", SELECTION_PATH, "401", id="selection-401"),
    pytest.param("post", SELECTION_PATH, "403", id="selection-403"),
    pytest.param("post", SELECTION_PATH, "503", id="selection-503"),
]


def BuildTestSettings() -> Settings:
    """Return Settings with a generated key, the allow-listed origin and an unused database."""
    return Settings(
        _env_file=None,
        APP_ENV=TEST_APP_ENV,
        SECRET_KEY=secrets.token_urlsafe(SECRET_KEY_BYTES),
        DATABASE_URL=UNUSED_DATABASE_URL.format(driver="asyncpg"),
        SYNC_DATABASE_URL=UNUSED_DATABASE_URL.format(driver="psycopg2"),
        BACKEND_CORS_ORIGINS=ALLOWED_ORIGIN,
    )


def InvalidSelectionBody() -> dict[str, object]:
    """Return the body cousr00c sends for an invalid selection code on the browsed page."""
    browsedPage = UserListResponse(
        rows=BROWSED_ROWS,
        page=BROWSED_PAGE,
        first_key=BROWSED_ROWS[0].user_id,
        last_key=BROWSED_ROWS[-1].user_id,
    )
    return cousr00c._InvalidSelectionRefusal(browsedPage).Body()


def DeclaredModel(document: dict[str, Any], operation: tuple[str, str], status: str) -> str:
    """Return the component name the JSON schema of ``operation``'s ``status`` references."""
    method, path = operation
    response = document["paths"][path][method]["responses"][status]
    reference = response["content"][JSON_MEDIA_TYPE]["schema"]["$ref"]
    return reference.removeprefix(SCHEMA_REFERENCE_PREFIX)


@pytest_asyncio.fixture(name="openApiDocument", scope="module")
async def OpenApiDocument() -> AsyncIterator[dict[str, Any]]:
    """Yield the OpenAPI document of CreateApp's app; dispose of its never-connected engine.

    app.main is imported here, not at module level, as in the shared testApp fixture.
    """
    from app.main import CreateApp

    application = CreateApp(BuildTestSettings())
    yield application.openapi()
    await DisposeEngine(application.state.engine)


def test_selection_400_declares_every_key_of_the_invalid_selection_body(openApiDocument):
    selectionOperation = ("post", SELECTION_PATH)
    declaredModel = DeclaredModel(openApiDocument, selectionOperation, EDIT_FAILURE_STATUS)
    declaredSchema = openApiDocument["components"]["schemas"][declaredModel]
    assert declaredModel == SELECTION_ERROR_MODEL
    assert set(declaredSchema["properties"]) == set(InvalidSelectionBody())


def test_invalid_selection_body_validates_against_its_declared_model_unchanged():
    refusalBody = InvalidSelectionBody()
    declaredBody = UserSelectionErrorResponse.model_validate(refusalBody)
    assert declaredBody.model_dump(mode="json") == refusalBody


@pytest.mark.parametrize(("method", "path", "status"), LEGACY_ERROR_CASES)
def test_other_admin_user_errors_keep_the_legacy_error_model(openApiDocument, method, path, status):
    assert DeclaredModel(openApiDocument, (method, path), status) == LEGACY_ERROR_MODEL
