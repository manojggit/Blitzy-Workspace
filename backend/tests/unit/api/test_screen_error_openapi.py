"""Unit tests of the error models the CAUP, CCLI, CCUP and CT00 routes declare in OpenAPI.

Some legacy outcomes of these routes add keys beside the four legacy error keys:

- COACTUPC (CAUP) and COCRDUPC (CCUP) send the screen ``fields``, ``state`` and
    ``screen_token`` with every 400, 404, 409, 423 and 503 (coactupc.RaiseScreenError,
    cocrdupc.ScreenError);
- a COCRDLIC (CCLI) selection error adds the redisplayed ``rows``, ``first_key`` and
    ``last_key``, and on GET /api/v1/cards the ``page`` (cocrdlic.SelectionError);
- a COTRN00C (CT00) invalid selection code adds the browsed page's ``rows``, ``page``,
    ``first_key``, ``last_key`` and ``search_cleared`` (cotrn00c._InvalidSelectionRefusal).

The declared responses must be complete for the contract tests, as specified in the Technical
Specification, Section 0.10.5. Each status that can carry the keys references the model
declaring them, whose properties are exactly the keys the service builds and which every such
body validates against unchanged; every other status keeps LegacyErrorResponse; and a
four-key body still validates against each extended model.

The document is generated by CreateApp from Settings whose engine never connects, and the
bodies are built without a request or a database. SECRET_KEY is generated with the secrets
module and backend/.env is never read (_env_file=None).
"""

