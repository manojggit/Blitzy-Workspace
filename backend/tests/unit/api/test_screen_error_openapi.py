def OfflineContext() -> OnlineContext:
    """Return an OnlineContext that only signs screen tokens: it serves no request or session."""
    return OnlineContext(
        request=Request({"type": "http"}), session=AsyncSession(), settings=TEST_SETTINGS
    )


def RaisedBody(raiseError: Callable[[], object]) -> dict[str, object]:
    """Return the body of the LegacyMessageError that calling ``raiseError`` raises."""
    with pytest.raises(LegacyMessageError) as raised:
        raiseError()
    return raised.value.Body()


def AccountKeyEditBody() -> dict[str, object]:
    """Return the CAUP 400 of a key failing 1210-EDIT-ACCOUNT: the DETAILS_NOT_FETCHED screen."""
    outcome = coactupc.KeyErrorOutcome(INVALID_ACCOUNT_FILTER, coactupc.MSG_ACCOUNT_KEY_INVALID)
    return RaisedBody(lambda: coactupc.RaiseScreenError(outcome, OfflineContext()))


def AccountLockFailureBody() -> dict[str, object]:
    """Return the CAUP 423 of an F5 that cannot lock the account: CHANGES_FAILED."""
    newValues = coactupc.NewAccountData(texts=CONFIRMED_ACCOUNT_TEXTS, amounts={})
    confirmedState = coactupc.AccountUpdateState(
        UpdateScreenState.CHANGES_OK_NOT_CONFIRMED,
        SAMPLE_ACCOUNT_ID,
        SAMPLE_CUSTOMER_ID,
        newValues=newValues,
    )
    attempt = coactupc.WriteAttempt(outcome=coactupc.OUTCOME_ACCOUNT_LOCK_FAILED)
    outcome = coactupc.SaveOutcome(confirmedState, attempt)
    return RaisedBody(lambda: coactupc.RaiseScreenError(outcome, OfflineContext()))


def CardNotFoundBody() -> dict[str, object]:
    """Return the CCUP 404 of a card 9100-GETCARD-BYACCTCARD does not find: the key screen."""
    shownKeys = (SAMPLE_ACCOUNT_ID, SAMPLE_CARD_NUMBER)
    failedFields = (ACCT_ID_FIELD, CARD_NUM_FIELD)
    reply = cocrdupc.ReadFailureReply(shownKeys, CARD_NOT_FOUND_MESSAGE, failedFields)
    return cocrdupc.ScreenError(reply, HTTP_NOT_FOUND, TEST_SETTINGS).Body()


def CardRecordChangedBody() -> dict[str, object]:
    """Return the CCUP 409 of an F5 finding the card changed: SHOW_DETAILS, fresh record shown."""
    freshImage = cocrdupc.BeforeImage(
        cvv="000", name="FRESH NAME", year="2030", month="01", day="31", status="Y"
    )
    confirmedState = cocrdupc.CardUpdateState(
        cocrdupc.STATE_CONFIRM, SAMPLE_ACCOUNT_ID, SAMPLE_CARD_NUMBER
    )
    attempt = cocrdupc.WriteAttempt(outcome=cocrdupc.OUTCOME_CHANGED, freshImage=freshImage)
    changedScreen = cocrdupc.WRITE_OUTCOMES[cocrdupc.OUTCOME_CHANGED]
    reply = cocrdupc.WriteOutcomeReply(confirmedState, attempt, changedScreen)
    return cocrdupc.ScreenError(reply, changedScreen.httpStatus, TEST_SETTINGS).Body()


def RedisplayedCardsBody(*, withPage: bool) -> dict[str, object]:
    """Return the CCLI 400 of an invalid selection code over two redisplayed cards."""
    cardRecords = tuple(
        {"card_num": cardNum, "acct_id": SAMPLE_ACCOUNT_ID, "active_status": "Y"}
        for cardNum in (SAMPLE_CARD_NUMBER, SECOND_CARD_NUMBER)
    )
    selection = cocrdlic.EditSelections(INVALID_ROW_CODES)
    state = cocrdlic.ListState(
        cursor=cocrdlic.FRESH_CURSOR,
        pageNumber=REDISPLAY_PAGE,
        message=selection.message,
        rows=cardRecords,
    )
    return cocrdlic.SelectionError(state, selection, TEST_SETTINGS, withPage=withPage).Body()


def CardFilterFailureBody() -> dict[str, object]:
    """Return the CCLI 400 of an account filter failing 2210-EDIT-ACCOUNT: four keys only."""
    filterEdit = cocrdlic.EditFilters(INVALID_ACCOUNT_FILTER, "")
    return RaisedBody(lambda: cocrdlic.RaiseFilterError(filterEdit))


def InvalidTransactionSelectionBody() -> dict[str, object]:
    """Return the CT00 400 of an invalid selection code over the browsed page."""
    tranRecord = {
        "tran_id": SAMPLE_TRAN_ID,
        "orig_ts": SAMPLE_TRAN_TIMESTAMP,
        "orig_ts_format": TIMESTAMP_FORMAT_SPACE,
        "tran_desc": "PURCHASE AT A SAMPLE MERCHANT",
        "tran_amt": SAMPLE_TRAN_AMOUNT,
    }
    state = cotrn00c.ListState(
        firstKey=SAMPLE_TRAN_ID,
        lastKey=SAMPLE_TRAN_ID,
        page=REDISPLAY_PAGE,
        message=cotrn00c.INVALID_SELECTION_MESSAGE,
        rows=[tranRecord],
        searchCleared=True,
    )
    return cotrn00c._InvalidSelectionRefusal(state).Body()


def NonNumericSearchBody() -> dict[str, object]:
    """Return the CT00 400 of a non-numeric search key, as cotrn00c raises it: four keys only."""
    return LegacyMessageError(
        cotrn00c.TRAN_ID_NOT_NUMERIC_MESSAGE, field=cotrn00c.SEARCH_CURSOR_FIELD
    ).Body()


def FourKeyBody() -> dict[str, object]:
    """Return a legacy error body holding only the four standard keys."""
    return ErrorBody(FOUR_KEY_MESSAGE, ACCT_ID_FIELD)


