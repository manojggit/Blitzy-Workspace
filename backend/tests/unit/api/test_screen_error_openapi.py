def DeclaredErrorModels(document: dict[str, Any], operation: tuple[str, str]) -> dict[str, str]:
    """Return ``{status: component name}`` for every legacy error status ``operation`` declares."""
    method, path = operation
    responses = document["paths"][path][method]["responses"]
    return {
        status: response["content"][JSON_MEDIA_TYPE]["schema"]["$ref"].removeprefix(
            SCHEMA_REFERENCE_PREFIX
        )
        for status, response in responses.items()
        if status not in NON_LEGACY_STATUSES
    }


def ComponentValidator(document: dict[str, Any], componentName: str) -> jsonschema_rs.Validator:
    """Return a validator of component ``componentName``, with every component resolvable."""
    rootSchema = {
        "$ref": SCHEMA_REFERENCE_PREFIX + componentName,
        "components": document["components"],
    }
    return jsonschema_rs.Draft202012Validator(rootSchema)


@pytest_asyncio.fixture(name="openApiDocument", scope="module")
async def OpenApiDocument() -> AsyncIterator[dict[str, Any]]:
    """Yield the OpenAPI document of CreateApp's app; dispose of its never-connected engine.

    app.main is imported here, not at module level, as in the shared testApp fixture.
    """
    from app.main import CreateApp

    application = CreateApp(BuildTestSettings())
    yield application.openapi()
    await DisposeEngine(application.state.engine)


@pytest.mark.parametrize(("operation", "expectedModels"), DECLARED_ERROR_MODEL_CASES)
def test_each_error_status_references_the_model_of_the_keys_it_can_carry(
    openApiDocument, operation, expectedModels
):
    assert DeclaredErrorModels(openApiDocument, operation) == expectedModels


@pytest.mark.parametrize(("errorModel", "buildBody"), EXTENDED_BODY_CASES)
def test_declared_model_properties_are_exactly_the_service_body_keys(
    openApiDocument, errorModel, buildBody
):
    component = openApiDocument["components"]["schemas"][errorModel.__name__]
    assert set(component["properties"]) == set(buildBody())
    assert component["required"] == REQUIRED_KEYS


@pytest.mark.parametrize(("errorModel", "buildBody"), EXTENDED_BODY_CASES)
def test_service_body_validates_against_its_declared_model_unchanged(
    openApiDocument, errorModel, buildBody
):
    serviceBody = buildBody()
    ComponentValidator(openApiDocument, errorModel.__name__).validate(serviceBody)
    assert errorModel.model_validate(serviceBody).model_dump(mode="json") == serviceBody


@pytest.mark.parametrize(("errorModel", "buildBody"), FOUR_KEY_BODY_CASES)
def test_four_key_body_validates_against_the_extended_model(openApiDocument, errorModel, buildBody):
    fourKeyBody = buildBody()
    assert set(fourKeyBody) == set(LegacyErrorResponse.model_fields)
    ComponentValidator(openApiDocument, errorModel.__name__).validate(fourKeyBody)
    assert errorModel.model_validate(fourKeyBody).message == fourKeyBody["message"]
